import type { FastifyBaseLogger } from 'fastify';
import type { Env } from '../config/env.js';
import { AppError } from '../errors.js';
import type { ChatModel } from './chat-model.js';
import { createFakeChatModel } from './fake-chat.js';
import { createOpenAIChatModel } from './openai-chat.js';

export type { ChatModel } from './chat-model.js';

/** Pick the chat model from config. Called once at startup. */
export function createChatModel(
  env: Pick<Env, 'CHAT_PROVIDER' | 'CHAT_MODEL' | 'OPENAI_API_KEY'>,
  log: FastifyBaseLogger,
): ChatModel {
  if (env.CHAT_PROVIDER === 'fake') {
    log.warn('CHAT_PROVIDER=fake: answers are extracted sentences, NOT generated by an LLM');
    return createFakeChatModel(undefined, 25); // small delay so streaming is visible in the UI
  }
  if (env.OPENAI_API_KEY) return createOpenAIChatModel(env.OPENAI_API_KEY, env.CHAT_MODEL, log);

  log.warn('OPENAI_API_KEY is not set: /chat will be unavailable');
  return {
    provider: 'openai',
    model: env.CHAT_MODEL,
    async completeJson() {
      throw new AppError(
        503,
        'CHAT_NOT_CONFIGURED',
        'Chat is not configured. Set OPENAI_API_KEY, or CHAT_PROVIDER=fake for offline testing.',
      );
    },
  };
}
